// Renders the members list and the glossary cards.
// Data lives in src/data/members.json and src/glossary/*.json.

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

async function loadJSON(path) {
  const response = await fetch(path, { cache: "no-store" });
  if (!response.ok) throw new Error(`${path}: ${response.status}`);
  return response.json();
}

async function renderMembers() {
  const list = document.getElementById("member-list");
  try {
    const members = await loadJSON("data/members.json");
    for (const member of members) {
      const card = el("div", "card member");
      const avatar = el("img");
      avatar.src = `https://github.com/${encodeURIComponent(member.github)}.png?size=96`;
      avatar.alt = "";
      avatar.loading = "lazy";

      const text = el("div");
      text.append(el("p", "name", member.name));
      const handle = el("p", "handle");
      const link = el("a", "", `@${member.github}`);
      link.href = `https://github.com/${encodeURIComponent(member.github)}`;
      handle.append(link);
      text.append(handle);
      if (member.role) text.append(el("span", "role", member.role));

      card.append(avatar, text);
      list.append(card);
    }
  } catch (error) {
    list.append(el("p", "empty", "Couldn't load members.json. Is it valid JSON?"));
    console.error(error);
  }
}

async function renderGlossary() {
  const list = document.getElementById("glossary-list");
  try {
    // glossary/index.json is generated by tools/build_glossary.py on deploy.
    const files = await loadJSON("glossary/index.json");
    const cards = await Promise.all(files.map((file) => loadJSON(`glossary/${file}`)));
    cards.sort((a, b) => a.term.localeCompare(b.term));
    for (const card of cards) {
      const node = el("div", "card");
      node.append(el("p", "term", card.term));
      node.append(el("p", "meaning", card.meaning));
      if (card.example) node.append(el("code", "example", card.example));
      list.append(node);
    }
  } catch (error) {
    list.append(el("p", "empty", "The glossary is built when the site deploys. To preview it locally, run python3 tools/build_glossary.py first."));
    console.error(error);
  }
}

renderMembers();
renderGlossary();
